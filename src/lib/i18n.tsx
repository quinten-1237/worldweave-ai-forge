interface I18nContext { lang: LanguageCode; setLang: (l: LanguageCode) => void; t: (k: string) => string; }
const Ctx = createContext<I18nContext>({ lang: "en", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>("en");

  useEffect(() => {
    const stored = (typeof window !== "undefined" && (localStorage.getItem("sf_lang") as LanguageCode)) || "en";
    if (stored && D[stored]) setLangState(stored);
  }, []);

  const setLang = (l: LanguageCode) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("sf_lang", l);
  };

  const t = (k: string) => D[lang]?.[k] ?? D.en[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
export const useT = () => useContext(Ctx).t;
